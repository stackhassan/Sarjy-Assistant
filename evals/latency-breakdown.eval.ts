import { existsSync, readFileSync } from "node:fs";
import { expect, it } from "vitest";
import { fmt, pct, runCase, stamp, writeResults } from "./lib/harness";

/**
 * Where does "first token" time go, guards ON vs OFF? Same conditions as the latency eval
 * that showed ON ~1.1 s slower (same chat prompts, order alternated per pair, the
 * harness's 7 s pacing), with the chat call split into stages:
 *   llmRequest      turn start → chat request sent (our own work before the call)
 *   llmHeaders      → response headers (connection + Groq queue + prompt processing)
 *   firstReasoning  → first reasoning chunk (the model has started "thinking")
 *   firstToken      → first answer text (thinking done)
 * plus Groq's own queue_time and the reasoning-token count from the final chunk.
 */

const CHAT = [
  "Hi Sarjy, how's it going?",
  "Tell me a fun fact about octopuses.",
  "What's the capital of Australia?",
  "Give me one tip for sleeping better.",
  "Recommend a good book for a long flight.",
  "What's a quick healthy breakfast idea?",
];
const REPS = Number(process.env.BREAKDOWN_REPS ?? 3);
const KEYS = ["llmRequest", "llmHeaders", "firstReasoning", "firstToken", "firstSentence", "groqQueueMs", "reasoningTokens", "inputGuards"] as const;

type Row = { prompt: string; guards: boolean; provider?: string; t: Record<string, number> };

/** BREAKDOWN_REGRADE=1 rebuilds the report from the saved rows without calling any model. */
const REGRADE = process.env.BREAKDOWN_REGRADE === "1";
const SAVED = "evals/results/latency-breakdown.json";

it.runIf(REGRADE && existsSync(SAVED))("latency breakdown: rebuild report from saved rows", () => {
  const rows = JSON.parse(readFileSync(SAVED, "utf8")) as Row[];
  writeResults("latency-breakdown", report(rows), rows);
  expect(rows.length).toBeGreaterThan(0);
});

it.skipIf(REGRADE)("latency breakdown: guards on vs off", async () => {
  const rows: Row[] = [];
  for (let rep = 0; rep < REPS; rep++) {
    for (const [i, prompt] of CHAT.entries()) {
      for (const guards of (rep + i) % 2 === 0 ? [true, false] : [false, true]) {
        const run = await runCase(prompt, { bypassGuards: !guards });
        rows.push({ prompt, guards, provider: run.provider, t: run.timings });
        console.log(`${guards ? "ON " : "OFF"} ${JSON.stringify(Object.fromEntries(KEYS.map((k) => [k, run.timings[k]])))} ${run.provider}`);
      }
    }
  }

  writeResults("latency-breakdown", report(rows), rows);
  expect(rows.length).toBe(REPS * CHAT.length * 2);
});

function report(rows: Row[]): string {
  // Compare like with like: the model most turns ran on (the primary can hit its daily cap
  // mid-run, and then both arms fail over to the same fallback).
  const counts = new Map<string, number>();
  for (const r of rows) if (r.provider) counts.set(r.provider, (counts.get(r.provider) ?? 0) + 1);
  const model = [...counts].sort((a, b) => b[1] - a[1])[0]?.[0] ?? "";
  const clean = rows.filter((r) => r.provider === model);
  const col = (guards: boolean, k: string) => clean.filter((r) => r.guards === guards).map((r) => r.t[k]).filter((n) => n !== undefined);
  const stage = (k: string, label: string) => {
    const on = col(true, k);
    const off = col(false, k);
    const d = pct(on, 50) - pct(off, 50);
    return `| ${label} | ${fmt(pct(on, 50))} | ${fmt(pct(off, 50))} | ${Number.isFinite(d) ? (d >= 0 ? "+" : "") + fmt(d) : "–"} | ${on.length} / ${off.length} |`;
  };
  // Paired: same prompt and rep, ON minus OFF.
  const pairs: number[] = [];
  for (let i = 0; i + 1 < rows.length; i += 2) {
    const [a, b] = [rows[i], rows[i + 1]];
    if (a.provider !== model || b.provider !== model) continue;
    const on = a.guards ? a : b;
    const off = a.guards ? b : a;
    if (on.t.firstToken !== undefined && off.t.firstToken !== undefined) pairs.push(on.t.firstToken - off.t.firstToken);
  }
  const onSlower = pairs.filter((d) => d > 0).length;

  const net = (guards: boolean) =>
    clean.filter((r) => r.guards === guards && r.t.llmHeaders !== undefined && r.t.groqQueueMs !== undefined).map((r) => r.t.llmHeaders - r.t.llmRequest - r.t.groqQueueMs);
  return `# Latency breakdown: guards ON vs OFF

_Generated by \`npm run evals:latency-breakdown\` on ${stamp()}: ${rows.length / 2} ON/OFF pairs of chat prompts, alternated per pair, 7 s pacing (the latency eval's conditions). Compared on the model both arms ran on: **${model}** (${clean.length} of ${rows.length} turns; the rest were served by another model and are excluded)._

Medians in ms (tokens for the last row), each stage measured from turn start:

| Stage | Guards ON | Guards OFF | Δ | n |
|---|---|---|---|---|
${stage("llmRequest", "Chat request sent")}
${stage("llmHeaders", "Response headers (connection + queue + prompt processing)")}
${stage("firstReasoning", "First reasoning chunk")}
${stage("firstToken", "First answer token")}
${stage("firstSentence", "First sentence out")}
${stage("groqQueueMs", "Groq queue time (reported by Groq)")}
${stage("reasoningTokens", "Reasoning tokens before answering")}
${stage("inputGuards", "Input guards (ON only)")}
| Network + connection (headers − request sent − Groq queue) | ${fmt(pct(net(true), 50))} | ${fmt(pct(net(false), 50))} | ${fmt(pct(net(true), 50) - pct(net(false), 50))} | ${net(true).length} / ${net(false).length} |

**Paired first-token difference (ON − OFF, same prompt and rep):** median ${fmt(pct(pairs, 50))} ms; ON slower in ${onSlower} of ${pairs.length} pairs.
`;
}
