import { expect, it } from "vitest";
import { screenInput } from "@/lib/guardrails";
import { screenOutput } from "@/lib/guardrails/l4-output";
import { systemPrompt } from "@/lib/prompts";
import { sleep, withContext, type ChaosFlag } from "@/lib/reliability/context";
import { fmt, pct, runCase, stamp, writeResults } from "./lib/harness";

/**
 * Guard budgets + hedging, live. The case that matters is a *slow* primary guard (it
 * hangs rather than failing fast): before hedging it used most of the input budget before
 * its own timeout, so the backups had no time and the turn went to safe mode.
 *   normal       no fault: how long guards take, and how often the hedge fires anyway
 *   guard_slow   primary guard models hang until their timeout
 */

const PROMPTS = [
  "What's a good name for a goldfish?",
  "Tell me a fun fact about octopuses.",
  "Give me one tip for sleeping better.",
  "What's the capital of Australia?",
  "Recommend a book for a long flight.",
  "Why is the sky blue?",
];
const N = Number(process.env.HEDGE_N ?? 8);
const sp = systemPrompt({ now: new Date(), timeZone: "Asia/Karachi" });

type Arm = { gateMs: number[]; viaBackup: number; degraded: number; blocked: number; l4Ms: number[]; l4Degraded: number; turnMs: number[]; safeMode: number; why: string[]; chatOnBackup: number };
const empty = (): Arm => ({ gateMs: [], viaBackup: 0, degraded: 0, blocked: 0, l4Ms: [], l4Degraded: 0, turnMs: [], safeMode: 0, why: [], chatOnBackup: 0 });

it("guard hedging: normal vs a slow primary guard", async () => {
  const arms: Record<string, Arm> = { normal: empty(), guard_slow: empty() };
  for (let i = 0; i < N; i++) {
    const text = PROMPTS[i % PROMPTS.length];
    for (const name of i % 2 ? ["guard_slow", "normal"] : ["normal", "guard_slow"]) {
      const chaos = new Set<ChaosFlag>(name === "guard_slow" ? ["guard_slow"] : []);
      const a = arms[name];
      // Input gate (L1 + L2 in parallel), as a turn runs it.
      const t0 = performance.now();
      const screen = await withContext({ chaos }, () => screenInput({ text, history: [] }));
      a.gateMs.push(Math.round(performance.now() - t0));
      if (screen.results.some((r) => /via backup/.test(r.reason))) a.viaBackup++;
      if (screen.risk.degraded) a.degraded++;
      if (screen.blocked) a.blocked++;
      // L4's LLM tier on a sentence that triggers it (dosing-shaped wording, harmless content).
      const t1 = performance.now();
      const l4 = await withContext({ chaos }, () =>
        screenOutput({ sentence: "Take two deep breaths every few minutes to relax.", userText: text, systemPrompt: sp, risk: { reasons: ["eval: force LLM tier"] } }),
      );
      a.l4Ms.push(Math.round(performance.now() - t1));
      if (l4.verdict === "degraded" || /unavailable/.test(l4.reason)) a.l4Degraded++;
      // A full turn.
      const run = await runCase(text, { chaos: [...chaos] });
      if (run.timings.firstSentence !== undefined) a.turnMs.push(run.timings.firstSentence);
      if (run.provider && run.provider !== "groq/gpt-oss-120b") a.chatOnBackup++;
      if (run.events.some((e) => e.type === "recovery" && e.action === "safe mode")) {
        a.safeMode++;
        const degraded = run.events.filter((e) => e.type === "guard" && e.verdict === "degraded").map((e) => (e.type === "guard" ? `${e.layer}: ${e.reason}` : ""));
        a.why.push(`${text} [chat on ${run.provider}] ${degraded.join(" | ").slice(0, 300)}`);
      }
      await sleep(1500);
    }
  }

  const row = (name: string) => {
    const a = arms[name];
    return `| ${name} | ${a.chatOnBackup} / ${N} | ${fmt(pct(a.gateMs, 50))} / ${fmt(pct(a.gateMs, 95))} | ${a.viaBackup} / ${a.gateMs.length} | ${a.degraded} | ${fmt(pct(a.l4Ms, 50))} / ${fmt(pct(a.l4Ms, 95))} | ${a.l4Degraded} | ${fmt(pct(a.turnMs, 50))} / ${fmt(pct(a.turnMs, 95))} | ${a.safeMode} / ${N} |`;
  };
  const md = `# Guard hedging and time budgets

_Generated by \`npm run evals:guard-hedge\` on ${stamp()}: ${N} rounds per arm, arms alternated._

Each guard call has one time budget shared by its whole backup chain (input 2.5 s, L4 2.2 s per sentence). If the primary hasn't answered by 700 ms (safeguard) or 500 ms (Prompt Guard), the first backup starts alongside it and the first good answer wins. \`guard_slow\` makes the primary guard models hang until their timeout: the slow outage that, without hedging, used up the budget before any backup could run.

| Arm | Chat on a fallback model | Input gate p50 / p95 (ms) | L2 answered by a backup | Input degraded | L4 LLM check p50 / p95 (ms) | L4 degraded | Turn first sentence p50 / p95 (ms) | Turns in safe mode |
|---|---|---|---|---|---|---|---|---|
${row("normal")}
${row("guard_slow")}

${[...arms.normal.why, ...arms.guard_slow.why].map((w) => `- Safe mode: ${w}`).join("\n") || "No turn went to safe mode."}
`;
  writeResults("guard-hedge", md, arms);
  expect(arms.normal.gateMs.length).toBe(N);
});
