import { expect, it } from "vitest";
import { promptGuardScore, safeguardClassify } from "@/lib/guardrails/classifiers";
import { TOPIC_POLICY } from "@/lib/guardrails/l2-topic";
import { MODELS } from "@/lib/llm/models";
import { systemPrompt } from "@/lib/prompts";
import { sleep } from "@/lib/reliability/context";
import { fmt, pct, runCase, stamp, writeResults } from "./lib/harness";

/**
 * Why were guards-ON turns ~1.1 s slower to first sentence in the latency eval, when the
 * guards themselves finish in ~150 ms and never hold a sentence back (guardWait ≈ 0)?
 * The saved samples show the gap is in the chat model's *first token*, so either the
 * guard calls slow the chat request on the same Groq key, or it's run-to-run noise.
 *
 * Arms, interleaved in rotating order so drift in Groq's load hits all of them equally:
 *   A  chat request alone (Sarjy's real system prompt)
 *   B  the same request with Prompt Guard + safeguard fired at the same moment (as the app does)
 *   C  a full turn, guards on        D  a full turn, guards off
 * For A/B we also record Groq's own `queue_time`, which says directly whether the request
 * waited in Groq's queue.
 */

const PROMPTS = [
  "Tell me a fun fact about octopuses.",
  "What's the capital of Australia?",
  "Give me one tip for sleeping better.",
  "Recommend a good book for a long flight.",
  "What's a quick healthy breakfast idea?",
  "Why is the sky blue?",
];
const ROUNDS = Number(process.env.CONTENTION_ROUNDS ?? 12);

type Raw = { firstToken: number; queueMs: number | null };

async function rawChat(prompt: string, withGuards: boolean): Promise<Raw> {
  const sys = systemPrompt({ now: new Date(), timeZone: "Asia/Karachi" });
  const chat = (async (): Promise<Raw> => {
    const t0 = performance.now();
    const res = await fetch("https://api.groq.com/openai/v1/chat/completions", {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: `Bearer ${process.env.GROQ_API_KEY}` },
      body: JSON.stringify({
        model: MODELS.chat,
        messages: [{ role: "system", content: sys }, { role: "user", content: prompt }],
        stream: true,
        reasoning_effort: "low",
        max_completion_tokens: 200,
      }),
    });
    if (!res.ok) throw new Error(`chat ${res.status}`);
    const reader = res.body!.pipeThrough(new TextDecoderStream()).getReader();
    let buf = "";
    let firstToken = NaN;
    for (;;) {
      const { value, done } = await reader.read();
      if (done) break;
      buf += value;
      if (Number.isNaN(firstToken) && buf.includes('"content":"')) firstToken = Math.round(performance.now() - t0);
    }
    // Groq reports per-request queue time in the final chunk's x_groq.usage.
    const q = buf.match(/"queue_time":\s*([\d.e-]+)/);
    return { firstToken, queueMs: q ? Math.round(Number(q[1]) * 1000) : null };
  })();
  if (!withGuards) return chat;
  const [r] = await Promise.all([
    chat,
    promptGuardScore(prompt),
    safeguardClassify(TOPIC_POLICY, `USER MESSAGE: ${prompt}`, { timeoutMs: 5000, budgetMs: 5000 }),
  ]);
  return r;
}

it("contention: do the guard calls slow the chat model?", async () => {
  const A: Raw[] = [];
  const B: Raw[] = [];
  const C: number[] = [];
  const D: number[] = [];
  const Cft: number[] = [];
  const Dft: number[] = [];
  const arms = ["A", "B", "C", "D"] as const;

  for (let i = 0; i < ROUNDS; i++) {
    const p = PROMPTS[i % PROMPTS.length];
    // Rotate the order each round (ABCD, BCDA, ...) so no arm always goes first.
    for (let k = 0; k < arms.length; k++) {
      const arm = arms[(i + k) % arms.length];
      try {
        if (arm === "A") A.push(await rawChat(p, false));
        if (arm === "B") B.push(await rawChat(p, true));
        if (arm === "C" || arm === "D") {
          const run = await runCase(p, { bypassGuards: arm === "D" });
          if (run.provider !== "groq/gpt-oss-120b" || run.timings.firstSentence === undefined) continue; // fallback model: not comparable
          (arm === "C" ? C : D).push(run.timings.firstSentence);
          (arm === "C" ? Cft : Dft).push(run.timings.firstToken);
        }
      } catch (err) {
        console.warn(`${arm}: ${(err as Error).message}`);
      }
      await sleep(2500); // stay under the free tier's tokens-per-minute limit
    }
  }

  const ft = (xs: Raw[]) => xs.map((x) => x.firstToken).filter(Number.isFinite);
  const q = (xs: Raw[]) => xs.map((x) => x.queueMs).filter((n): n is number => n !== null);
  const row = (label: string, v: number[]) => `| ${label} | ${fmt(pct(v, 50))} | ${fmt(pct(v, 95))} | ${v.length} |`;
  const md = `# Latency: do guards compete with the chat model?

_Generated by \`npm run evals:contention\` on ${stamp()}: ${ROUNDS} rounds, arms interleaved in rotating order._

The latency eval showed guards-ON turns ~1.1 s slower to first sentence (p50), yet the guards finish in ~150 ms and never hold a sentence back. The saved samples put the whole gap in the chat model's first token. This isolates the cause.

| Measure (ms) | p50 | p95 | n |
|---|---|---|---|
${row("A. Chat first token, alone", ft(A))}
${row("B. Chat first token, guard calls fired alongside", ft(B))}
${row("A. Groq queue time, alone", q(A))}
${row("B. Groq queue time, guards alongside", q(B))}
${row("C. Full turn first sentence, guards ON", C)}
${row("D. Full turn first sentence, guards OFF", D)}
${row("C. Full turn first token, guards ON", Cft)}
${row("D. Full turn first token, guards OFF", Dft)}
`;
  writeResults("contention", md, { A, B, C, D, Cft, Dft });
  expect(A.length + B.length).toBeGreaterThan(0);
});
